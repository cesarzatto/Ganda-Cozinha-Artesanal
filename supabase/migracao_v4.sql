-- Migração v3 → v4: número de pedido, entrega/pagamento/observação na
-- venda, validação de estoque ao vender, e preparação (status/título)
-- para a futura seção de Orçamentos. Não apaga nenhum dado.
-- Rode este arquivo no SQL Editor do Supabase.

-- 1) Novas colunas em "vendas"
alter table vendas add column if not exists numero_pedido integer generated by default as identity;
alter table vendas add column if not exists status text not null default 'confirmada';
alter table vendas add column if not exists titulo text;
alter table vendas add column if not exists forma_pagamento text;
alter table vendas add column if not exists data_entrega date;
alter table vendas add column if not exists observacao text;

-- garante que numero_pedido é único mesmo se a coluna já existia sem essa restrição
do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'vendas_numero_pedido_key'
  ) then
    alter table vendas add constraint vendas_numero_pedido_key unique (numero_pedido);
  end if;
end $$;

-- regras de valor permitido (idempotente: remove se já existir e recria)
alter table vendas drop constraint if exists vendas_status_check;
alter table vendas add constraint vendas_status_check check (status in ('orcamento', 'confirmada'));

alter table vendas drop constraint if exists vendas_forma_pagamento_check;
alter table vendas add constraint vendas_forma_pagamento_check
  check (forma_pagamento is null or forma_pagamento in ('dinheiro', 'pix', 'cartao', 'outro'));

-- cliente deixa de ser obrigatório na estrutura (a função registrar_venda
-- continua exigindo cliente para toda venda confirmada — isso só prepara
-- o banco para os orçamentos, que não têm cliente definido ainda)
alter table vendas alter column cliente_id drop not null;

-- 2) Substitui registrar_venda (agora valida estoque e aceita os campos novos)
drop function if exists registrar_venda(uuid, jsonb, numeric, numeric, text, date);

create or replace function registrar_venda(
  p_cliente_id uuid,
  p_itens jsonb,
  p_desconto numeric,
  p_valor_total numeric,
  p_forma_contato text,
  p_data_venda date,
  p_data_entrega date default null,
  p_forma_pagamento text default null,
  p_observacao text default null
) returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_venda_id uuid;
  v_item jsonb;
  v_produto_id uuid;
  v_quantidade integer;
  v_estoque_insuficiente record;
begin
  if p_cliente_id is null then
    raise exception 'Toda venda precisa estar vinculada a um cliente';
  end if;

  if p_itens is null or jsonb_array_length(p_itens) = 0 then
    raise exception 'A venda precisa ter pelo menos um produto';
  end if;

  select p.nome, p.estoque_atual, pedido.qtd
  into v_estoque_insuficiente
  from (
    select (elem ->> 'produto_id')::uuid as produto_id, sum((elem ->> 'quantidade')::integer) as qtd
    from jsonb_array_elements(p_itens) elem
    group by (elem ->> 'produto_id')::uuid
  ) pedido
  join produtos p on p.id = pedido.produto_id
  where p.estoque_atual < pedido.qtd
  limit 1;

  if v_estoque_insuficiente.nome is not null then
    raise exception 'Estoque insuficiente de "%": só há % em estoque.',
      v_estoque_insuficiente.nome, v_estoque_insuficiente.estoque_atual;
  end if;

  insert into vendas (cliente_id, valor_total, desconto, forma_contato, data_venda, data_entrega, forma_pagamento, observacao, status)
  values (
    p_cliente_id,
    p_valor_total,
    coalesce(p_desconto, 0),
    p_forma_contato,
    coalesce(p_data_venda, current_date),
    p_data_entrega,
    p_forma_pagamento,
    p_observacao,
    'confirmada'
  )
  returning id into v_venda_id;

  for v_item in select * from jsonb_array_elements(p_itens)
  loop
    v_produto_id := (v_item ->> 'produto_id')::uuid;
    v_quantidade := (v_item ->> 'quantidade')::integer;

    insert into venda_itens (venda_id, produto_id, quantidade, preco_unitario)
    values (v_venda_id, v_produto_id, v_quantidade, (v_item ->> 'preco_unitario')::numeric);

    update produtos
    set estoque_atual = estoque_atual - v_quantidade
    where id = v_produto_id;

    insert into movimentacoes_produtos (produto_id, tipo, quantidade, motivo, venda_id)
    values (v_produto_id, 'saida', v_quantidade, 'Venda', v_venda_id);
  end loop;

  return v_venda_id;
end;
$$;

grant execute on function registrar_venda(uuid, jsonb, numeric, numeric, text, date, date, text, text) to anon, authenticated;

-- 3) Nova função para editar entrega/pagamento/observação depois de criada
create or replace function atualizar_entrega_venda(
  p_venda_id uuid,
  p_data_entrega date,
  p_forma_pagamento text,
  p_observacao text
) returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  update vendas
  set data_entrega = p_data_entrega,
      forma_pagamento = p_forma_pagamento,
      observacao = p_observacao
  where id = p_venda_id;
end;
$$;

grant execute on function atualizar_entrega_venda(uuid, date, text, text) to anon, authenticated;
