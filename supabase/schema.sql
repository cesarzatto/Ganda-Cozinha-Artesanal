-- ==========================================================
-- CUSTO DE PRODUTO — funções recursivas (suportam sub-receitas: um
-- produto pode usar outro produto "não vendido separadamente" como
-- se fosse um ingrediente, ex: um brigadeiro dentro de um ovo de Páscoa)
-- ==========================================================

create or replace function custo_mao_obra_produto(p_produto_id uuid)
returns numeric
language sql
stable
as $$
  select (p.tempo_producao_minutos / 60.0) * cfg.valor_hora_trabalho / greatest(p.rendimento_lote, 1)
  from produtos p
  cross join configuracoes cfg
  where p.id = p_produto_id;
$$;

create or replace function custo_mao_obra_bruta_produto(p_produto_id uuid)
returns numeric
language sql
stable
as $$
  select (p.tempo_producao_minutos / 60.0) * cfg.valor_hora_trabalho
  from produtos p
  cross join configuracoes cfg
  where p.id = p_produto_id;
$$;

-- p_profundidade evita loop infinito se alguém acidentalmente criar uma
-- referência circular entre produtos (A usa B, B usa A)
--
-- Produtos "medidos" (rendimento_unidade_medida diferente de "unidade" —
-- sub-produtos OU produtos finais sob encomenda vendidos por peso/volume)
-- têm a ficha técnica preenchida com as quantidades da receita INTEIRA
-- (o lote), não de uma unidade — então tudo é somado com a mão de obra
-- crua (sem dividir por rendimento_lote) e dividido uma vez só pelo
-- rendimento, dando o custo por grama/ml/etc. Produtos com rendimento em
-- "unidade" continuam com o comportamento de sempre: ingredientes já
-- entram por unidade, só a mão de obra é dividida.
create or replace function custo_total_produto(p_produto_id uuid, p_profundidade integer default 0)
returns numeric
language plpgsql
stable
as $$
declare
  v_produto record;
  v_ingredientes numeric;
  v_indireto numeric;
begin
  if p_profundidade > 5 then
    raise exception 'Ficha técnica com referência circular (produtos usando um ao outro)';
  end if;

  select vendido_separadamente, rendimento_unidade_medida, rendimento_lote, custo_indireto_unidade
  into v_produto
  from produtos where id = p_produto_id;

  v_ingredientes := custo_ingredientes_produto(p_produto_id, p_profundidade);
  v_indireto := coalesce(v_produto.custo_indireto_unidade, 0);

  if coalesce(v_produto.rendimento_unidade_medida, 'unidade') <> 'unidade' then
    return (v_ingredientes + custo_mao_obra_bruta_produto(p_produto_id) + v_indireto)
      / greatest(coalesce(v_produto.rendimento_lote, 1), 0.001);
  end if;

  return v_ingredientes + custo_mao_obra_produto(p_produto_id) + v_indireto;
end;
$$;

create or replace function custo_ingredientes_produto(p_produto_id uuid, p_profundidade integer default 0)
returns numeric
language plpgsql
stable
as $$
declare
  v_total numeric := 0;
  v_item record;
begin
  for v_item in
    select insumo_id, sub_produto_id, quantidade
    from ficha_tecnica
    where produto_id = p_produto_id
  loop
    if v_item.insumo_id is not null then
      v_total := v_total + v_item.quantidade * coalesce((select custo_unitario from insumos where id = v_item.insumo_id), 0);
    elsif v_item.sub_produto_id is not null then
      v_total := v_total + v_item.quantidade * custo_total_produto(v_item.sub_produto_id, p_profundidade + 1);
    end if;
  end loop;
  return v_total;
end;
$$;

-- ==========================================================
-- VIEW: produtos com custo total e preço sugerido calculados
-- ==========================================================

create or replace view produtos_com_custo
with (security_invoker = true) as
select
  p.*,
  custo_ingredientes_produto(p.id)::numeric(10, 2) as custo_ingredientes,
  custo_mao_obra_produto(p.id)::numeric(10, 2) as custo_mao_obra,
  custo_total_produto(p.id)::numeric(10, 2) as custo_total,
  coalesce(p.margem_desejada, cfg.margem_padrao) as margem_usada,
  case
    when coalesce(p.margem_desejada, cfg.margem_padrao) >= 100 then null
    else (custo_total_produto(p.id) / (1 - coalesce(p.margem_desejada, cfg.margem_padrao) / 100.0))::numeric(10, 2)
  end as preco_sugerido
from produtos p
cross join configuracoes cfg;

