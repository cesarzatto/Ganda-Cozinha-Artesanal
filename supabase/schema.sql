-- p_itens: jsonb no formato [{"produto_id": "...", "quantidade": 2, "preco_unitario": 5.00}, ...]
create or replace function registrar_venda(
  p_cliente_id uuid,
  p_itens jsonb,
  p_desconto numeric,
  p_valor_total numeric,
  p_forma_contato text,
  p_data_venda date,
  p_data_entrega date default null,
  p_forma_pagamento text default null,
  p_observacao text default null,
  p_tipo_frete text default 'retirada',
  p_distancia_km_ida numeric default null,
  p_custo_entrega numeric default null,
  p_pago boolean default true,
  p_endereco_entrega text default null,
  p_sem_valor boolean default false,
  p_ifood boolean default false,
  p_titulo text default null,
  p_pedido_online boolean default false,
  p_telefone_pedido text default null,
  p_salvar_endereco_principal boolean default false
) returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_venda_id uuid;
  v_item jsonb;
  v_produto_id uuid;
  v_quantidade numeric;
  v_estoque_insuficiente record;
begin
  -- pedidos do iFood e da loja online não têm cliente obrigatoriamente
  -- cadastrado de antemão: usam só um nome (titulo) até alguém vincular
  -- um cadastro depois
  if not coalesce(p_ifood, false) and not coalesce(p_pedido_online, false) and p_cliente_id is null then
    raise exception 'Toda venda precisa estar vinculada a um cliente';
  end if;

  if p_itens is null or jsonb_array_length(p_itens) = 0 then
    raise exception 'A venda precisa ter pelo menos um produto';
  end if;

  -- valida estoque de produto final ANTES de gravar qualquer coisa
  -- (produtos "sob demanda" não têm estoque controlado, então ficam de fora)
  select p.nome, p.estoque_atual, pedido.qtd
  into v_estoque_insuficiente
  from (
    select (elem ->> 'produto_id')::uuid as produto_id, sum((elem ->> 'quantidade')::numeric) as qtd
    from jsonb_array_elements(p_itens) elem
    group by (elem ->> 'produto_id')::uuid
  ) pedido
  join produtos p on p.id = pedido.produto_id
  where not p.sob_demanda and p.estoque_atual < pedido.qtd
  limit 1;

  if v_estoque_insuficiente.nome is not null then
    raise exception 'Estoque insuficiente de "%": só há % em estoque.',
      v_estoque_insuficiente.nome, v_estoque_insuficiente.estoque_atual;
  end if;

  insert into vendas (
    cliente_id, valor_total, desconto, forma_contato, data_venda, data_entrega,
    forma_pagamento, observacao, status, tipo_frete, distancia_km_ida, custo_entrega, pago,
    endereco_entrega, sem_valor, ifood, titulo, pedido_online, telefone_pedido, salvar_endereco_principal
  )
  values (
    p_cliente_id,
    p_valor_total,
    coalesce(p_desconto, 0),
    p_forma_contato,
    coalesce(p_data_venda, current_date),
    p_data_entrega,
    p_forma_pagamento,
    p_observacao,
    'confirmada',
    coalesce(p_tipo_frete, 'retirada'),
    p_distancia_km_ida,
    p_custo_entrega,
    coalesce(p_pago, true),
    p_endereco_entrega,
    coalesce(p_sem_valor, false),
    coalesce(p_ifood, false),
    p_titulo,
    coalesce(p_pedido_online, false),
    p_telefone_pedido,
    coalesce(p_salvar_endereco_principal, false)
  )
  returning id into v_venda_id;

  for v_item in select * from jsonb_array_elements(p_itens)
  loop
    v_produto_id := (v_item ->> 'produto_id')::uuid;
    v_quantidade := (v_item ->> 'quantidade')::numeric;

    insert into venda_itens (venda_id, produto_id, quantidade, preco_unitario)
    values (v_venda_id, v_produto_id, v_quantidade, (v_item ->> 'preco_unitario')::numeric);

    -- produtos "sob demanda" não têm estoque controlado: não desconta nem loga movimentação
    if not coalesce((select sob_demanda from produtos where id = v_produto_id), false) then
      update produtos
      set estoque_atual = estoque_atual - v_quantidade
      where id = v_produto_id;

      insert into movimentacoes_produtos (produto_id, tipo, quantidade, motivo, venda_id)
      values (v_produto_id, 'saida', v_quantidade, 'Venda', v_venda_id);
    end if;
  end loop;

  return v_venda_id;
end;
$$;

create or replace function atualizar_entrega_venda(
  p_venda_id uuid,
  p_data_entrega date,
  p_forma_pagamento text,
  p_observacao text,
  p_tipo_frete text default 'retirada',
  p_distancia_km_ida numeric default null,
  p_custo_entrega numeric default null,
  p_pago boolean default true,
  p_endereco_entrega text default null
) returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_subtotal_itens numeric;
  v_desconto numeric;
  v_extras numeric;
begin
  select coalesce(sum(vi.preco_unitario * vi.quantidade), 0)
  into v_subtotal_itens
  from venda_itens vi
  where vi.venda_id = p_venda_id;

  select v.desconto,
         coalesce((
           select sum((e.value ->> 'quantidade')::numeric * (e.value ->> 'valor_unitario')::numeric)
           from jsonb_array_elements(v.itens_personalizados) e
         ), 0)
  into v_desconto, v_extras
  from vendas v where v.id = p_venda_id;

  update vendas
  set data_entrega = p_data_entrega,
      forma_pagamento = p_forma_pagamento,
      observacao = p_observacao,
      tipo_frete = coalesce(p_tipo_frete, 'retirada'),
      distancia_km_ida = p_distancia_km_ida,
      custo_entrega = p_custo_entrega,
      pago = coalesce(p_pago, true),
      endereco_entrega = p_endereco_entrega,
      valor_total = greatest(v_subtotal_itens + v_extras - coalesce(v_desconto, 0), 0) + coalesce(p_custo_entrega, 0)
  where id = p_venda_id;
end;
$$;

-- Troca os itens de uma venda já confirmada (ex: cliente pediu para
-- aumentar/diminuir a quantidade depois do pedido feito) e ajusta o estoque
-- pela diferença entre a quantidade antiga e a nova de cada produto —
-- produtos "sob demanda" ficam de fora, igual no registro original.
create or replace function atualizar_itens_venda(
  p_venda_id uuid,
  p_itens jsonb,
  p_desconto numeric
) returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_status text;
  v_custo_entrega numeric;
  v_extras numeric;
  v_tem_extras boolean;
  v_tolera_falta boolean;
  v_novo_subtotal numeric;
  v_diff record;
  v_item jsonb;
  v_pid text;
  v_antiga_baixa numeric;
  v_nova_baixa numeric;
  v_delta numeric;
  v_producao jsonb := '{}'::jsonb;
  v_restante numeric;
  v_linha_qtd numeric;
  v_linha_produzir numeric;
begin
  select v.status, v.custo_entrega,
         coalesce((
           select sum((e.value ->> 'quantidade')::numeric * (e.value ->> 'valor_unitario')::numeric)
           from jsonb_array_elements(v.itens_personalizados) e
         ), 0),
         jsonb_array_length(v.itens_personalizados) > 0,
         exists (select 1 from venda_itens vi where vi.venda_id = v.id and vi.qtd_produzir > 0)
  into v_status, v_custo_entrega, v_extras, v_tem_extras, v_tolera_falta
  from vendas v where v.id = p_venda_id;

  if v_status is null then
    raise exception 'Pedido não encontrado';
  end if;
  if v_status <> 'confirmada' then
    raise exception 'Esse pedido não pode ter os itens editados por aqui';
  end if;

  p_itens := coalesce(p_itens, '[]'::jsonb);
  if jsonb_array_length(p_itens) = 0 and not v_tem_extras then
    raise exception 'O pedido precisa ter pelo menos um produto';
  end if;

  for v_diff in
    select
      coalesce(novo.produto_id, antigo.produto_id) as produto_id,
      coalesce(novo.qtd, 0) as novo_qtd,
      coalesce(antigo.qtd, 0) as antigo_qtd,
      coalesce(antigo.produzir, 0) as antigo_produzir,
      p.nome as produto_nome,
      p.estoque_atual as estoque_atual,
      p.sob_demanda as sob_demanda
    from (
      select produto_id, sum(quantidade) as qtd, sum(qtd_produzir) as produzir
      from venda_itens where venda_id = p_venda_id
      group by produto_id
    ) antigo
    full outer join (
      select (elem ->> 'produto_id')::uuid as produto_id, sum((elem ->> 'quantidade')::numeric) as qtd
      from jsonb_array_elements(p_itens) elem
      group by (elem ->> 'produto_id')::uuid
    ) novo on novo.produto_id = antigo.produto_id
    join produtos p on p.id = coalesce(novo.produto_id, antigo.produto_id)
  loop
    if v_diff.sob_demanda then
      v_producao := v_producao || jsonb_build_object(
        v_diff.produto_id::text,
        case when v_tolera_falta then v_diff.novo_qtd else 0 end
      );
      continue;
    end if;

    v_antiga_baixa := v_diff.antigo_qtd - v_diff.antigo_produzir;

    if v_tolera_falta then
      v_nova_baixa := least(v_diff.novo_qtd, greatest(v_diff.estoque_atual + v_antiga_baixa, 0));
    else
      v_nova_baixa := v_diff.novo_qtd;
    end if;

    v_delta := v_nova_baixa - v_antiga_baixa;

    if v_delta > 0 and v_diff.estoque_atual < v_delta then
      raise exception 'Estoque insuficiente de "%": só há % em estoque.',
        v_diff.produto_nome, v_diff.estoque_atual;
    end if;

    if v_delta <> 0 then
      update produtos
      set estoque_atual = estoque_atual - v_delta
      where id = v_diff.produto_id;

      insert into movimentacoes_produtos (produto_id, tipo, quantidade, motivo, venda_id)
      values (
        v_diff.produto_id,
        case when v_delta > 0 then 'saida' else 'entrada' end,
        abs(v_delta),
        'Ajuste de pedido',
        p_venda_id
      );
    end if;

    v_producao := v_producao || jsonb_build_object(v_diff.produto_id::text, v_diff.novo_qtd - v_nova_baixa);
  end loop;

  delete from venda_itens where venda_id = p_venda_id;

  for v_item in select value from jsonb_array_elements(p_itens)
  loop
    v_pid := v_item ->> 'produto_id';
    v_linha_qtd := (v_item ->> 'quantidade')::numeric;
    v_restante := coalesce((v_producao ->> v_pid)::numeric, 0);
    v_linha_produzir := least(v_linha_qtd, v_restante);
    v_producao := v_producao || jsonb_build_object(v_pid, v_restante - v_linha_produzir);

    insert into venda_itens (venda_id, produto_id, quantidade, preco_unitario, qtd_produzir)
    values (p_venda_id, v_pid::uuid, v_linha_qtd, (v_item ->> 'preco_unitario')::numeric, v_linha_produzir);
  end loop;

  select coalesce(sum(preco_unitario * quantidade), 0) into v_novo_subtotal
  from venda_itens where venda_id = p_venda_id;

  update vendas
  set desconto = coalesce(p_desconto, 0),
      valor_total = greatest(v_novo_subtotal + v_extras - coalesce(p_desconto, 0), 0) + coalesce(v_custo_entrega, 0)
  where id = p_venda_id;
end;
$$;

