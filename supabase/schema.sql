create table if not exists configuracoes (
  id integer primary key default 1,
  valor_hora_trabalho numeric(10, 2) not null default 30,
  margem_padrao numeric(5, 2) not null default 40,
  consumo_medio_km_l numeric(6, 2) not null default 10,
  preco_combustivel_litro numeric(6, 2) not null default 6.15,
  desgaste_por_km numeric(6, 2) not null default 0.30,
  velocidade_media_kmh numeric(6, 2) not null default 22,
  constraint configuracoes_id_unica check (id = 1)
);

insert into configuracoes (id, valor_hora_trabalho, margem_padrao)
values (1, 30, 40)
on conflict (id) do nothing;

