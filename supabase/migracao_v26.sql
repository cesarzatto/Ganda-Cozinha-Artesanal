-- Encomendas: pedidos "fora do catálogo", com itens digitados à mão
-- (descrição livre + quantidade + valor unitário). Não mexem em estoque
-- nem em produtos — por isso ficam numa tabela própria, separada de vendas.
-- Toda encomenda precisa de um cliente cadastrado (cliente_id); cliente_nome
-- guarda o nome na hora, pra notinha continuar certa se o cadastro sumir.
-- Cada item em "itens" é {"descricao": "...", "quantidade": 2, "valor_unitario": 35}.

create table if not exists encomendas (
  id uuid primary key default gen_random_uuid(),
  numero integer generated by default as identity unique,
  cliente_id uuid references clientes(id) on delete set null,
  cliente_nome text not null,
  endereco_entrega text,
  data_encomenda date not null default current_date,
  data_entrega date,
  itens jsonb not null default '[]'::jsonb,
  valor_total numeric not null default 0,
  forma_pagamento text,
  pago boolean not null default false,
  entregue boolean not null default false,
  notinha_impressa boolean not null default false,
  observacao text,
  created_at timestamptz not null default now()
);

alter table encomendas enable row level security;

drop policy if exists "acesso total encomendas" on encomendas;
create policy "acesso total encomendas" on encomendas for all using (true) with check (true);

grant all on encomendas to anon, authenticated;
